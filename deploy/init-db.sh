#!/bin/sh
set -eu
# 临时初始化服务器只接受 Unix socket；不能把初始超级用户当迁移账户再降权。
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$WRITING_APP_PASSWORD" --set=owner_password="$WRITING_OWNER_PASSWORD" <<'SQL'
BEGIN;
CREATE ROLE writing_owner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'owner_password';
CREATE ROLE writing_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'app_password';
ALTER DATABASE writing OWNER TO writing_owner;
ALTER SCHEMA public OWNER TO writing_owner;
REVOKE ALL ON DATABASE writing FROM PUBLIC;
GRANT CONNECT ON DATABASE writing TO writing_app;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO writing_app;
ALTER DEFAULT PRIVILEGES FOR ROLE writing_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO writing_app;
ALTER DEFAULT PRIVILEGES FOR ROLE writing_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO writing_app;
COMMIT;
SQL
